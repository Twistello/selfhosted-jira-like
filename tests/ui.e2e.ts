import {test,expect} from '@playwright/test';
import {randomBytes} from 'node:crypto';
import {totp} from '../server/core/crypto';

test('owner setup, project, task workflow, wiki, time and security',async({page})=>{
 await page.goto('/');
 await page.getByLabel('Ваше имя').fill('UI Tester');
 await page.getByLabel('Email',{exact:true}).fill('ui@example.test');
 const password=randomBytes(20).toString('hex');
 await page.getByLabel('Пароль',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Создать пространство'}).click();
 await page.getByRole('button',{name:'Создать проект',exact:true}).click();
 let dialog=page.getByRole('dialog');
 await dialog.getByLabel('Название',{exact:true}).fill('Команда разработки');
 await dialog.getByLabel('Ключ проекта').fill('TEAM');
 await dialog.getByRole('button',{name:'Создать проект',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Доска задач',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Создать задачу',exact:true}).click();
 dialog=page.getByRole('dialog');
 await dialog.getByLabel('Название задачи').fill('Проверить основной сценарий');
 await dialog.getByLabel('Описание · Markdown').fill('Рабочая задача из браузерного теста');
 await dialog.getByLabel('Story points').fill('3');
 await dialog.getByRole('button',{name:'Создать задачу',exact:true}).click();
 await expect(dialog).toBeHidden();
 await expect(page.locator('.task-card')).toContainText('Проверить основной сценарий');
 await page.locator('.task-card').click();
 dialog=page.getByRole('dialog');
 await dialog.getByRole('combobox',{name:'Статус',exact:true}).selectOption('ready');
 await dialog.getByRole('button',{name:'Сохранить',exact:true}).click();
 await expect(page.locator('.status-ready .task-card')).toHaveCount(1);
 await page.screenshot({path:'.runtime/ui-board-light.png',fullPage:true});
 await page.getByRole('button',{name:'Сменить тему'}).click();
 await page.screenshot({path:'.runtime/ui-board-dark.png',fullPage:true});
 await page.getByRole('button',{name:'Сменить тему'}).click();
 await page.reload();
 await expect(page.locator('.status-ready .task-card')).toHaveCount(1);
 await page.getByRole('button',{name:'Список',exact:true}).click();
 await expect(page.getByRole('table')).toContainText('TEAM-1');
 await page.getByRole('button',{name:'База знаний',exact:true}).click();
 await page.getByRole('button',{name:'Создать страницу',exact:true}).click();
 dialog=page.getByRole('dialog');
 await dialog.getByLabel('Заголовок').fill('Как работает команда');
 await dialog.getByLabel('Markdown',{exact:true}).fill('# Наш процесс\n\nПроверяем изменения перед выпуском.');
 await dialog.getByRole('button',{name:'Сохранить страницу'}).click();
 await expect(page.getByRole('heading',{name:'Наш процесс'})).toBeVisible();
 await page.screenshot({path:'.runtime/ui-wiki-light.png',fullPage:true});
 await page.getByRole('button',{name:'Сменить тему'}).click();
 await page.screenshot({path:'.runtime/ui-wiki-dark.png',fullPage:true});
 await page.getByRole('button',{name:'Сменить тему'}).click();
 await page.getByRole('button',{name:'Учёт времени',exact:true}).click();
 await page.getByRole('button',{name:'Записать время',exact:true}).click();
 dialog=page.getByRole('dialog');
 await dialog.getByLabel('Минуты',{exact:true}).fill('45');
 await dialog.getByLabel('Описание работы').fill('Проверка интерфейса');
 await dialog.getByRole('button',{name:'Записать время',exact:true}).click();
 await expect(page.getByRole('table')).toContainText('Проверка интерфейса');
 await expect(page.getByRole('table')).toContainText('45m');
 await page.getByRole('button',{name:'Отчёты',exact:true}).click();
 await expect(page.locator('.report-metrics')).toContainText('45');
 await page.screenshot({path:'.runtime/ui-reports-light.png',fullPage:true});
 await page.getByRole('button',{name:'Сменить тему'}).click();
 await page.screenshot({path:'.runtime/ui-reports-dark.png',fullPage:true});
 await page.getByRole('button',{name:'Сменить тему'}).click();
 await page.getByRole('button',{name:'Интеграции',exact:true}).click();
 await expect(page.getByRole('heading',{name:'GitLab пока не подключён'})).toBeVisible();
 await page.getByRole('button',{name:'Безопасность',exact:true}).click();
 await page.getByRole('button',{name:'Настроить 2FA'}).click();
 await expect(page.getByAltText('Authenticator QR code')).toBeVisible();
 const secret=await page.locator('details code').textContent();
 const code=totp(secret!);
 const enabling=page.waitForResponse(r=>r.url().endsWith('/auth/mfa/enable')&&r.request().method()==='POST');
 await page.getByLabel('Код подтверждения').fill(code);
 await page.getByRole('button',{name:'Включить 2FA',exact:true}).click();
 const recoveryCodes=(await (await enabling).json()).recoveryCodes as string[];
 await expect(page.getByRole('heading',{name:'Сохраните резервные коды'})).toBeVisible();
 await page.getByRole('button',{name:'Выйти из системы'}).click();
 const replay=await page.request.post('/api/v1/auth/login',{data:{email:'ui@example.test',password,code},headers:{Origin:'http://127.0.0.1:3001'}});
 expect(replay.ok()).toBeFalsy();
 await page.getByLabel('Email',{exact:true}).fill('ui@example.test');
 await page.getByLabel('Пароль',{exact:true}).fill(password);
 await page.getByLabel('Код 2FA или резервный код (если включено)').fill(recoveryCodes[0]);
 await page.getByRole('button',{name:'Войти в пространство'}).click();
 await expect(page.getByRole('heading',{name:'Доска задач',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Безопасность',exact:true}).click();
 await page.screenshot({path:'.runtime/ui-security-light.png',fullPage:true});
 await page.getByRole('button',{name:'Выйти из системы'}).click();
 const recoveryReplay=await page.request.post('/api/v1/auth/login',{data:{email:'ui@example.test',password,code:recoveryCodes[0]},headers:{Origin:'http://127.0.0.1:3001'}});
 expect(recoveryReplay.ok()).toBeFalsy();
 await page.getByLabel('Email',{exact:true}).fill('ui@example.test');
 await page.getByLabel('Пароль',{exact:true}).fill(password);
 await page.getByLabel('Код 2FA или резервный код (если включено)').fill(recoveryCodes[1]);
 await page.getByRole('button',{name:'Войти в пространство'}).click();
 await expect(page.getByRole('heading',{name:'Доска задач',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Безопасность',exact:true}).click();
 await page.getByRole('button',{name:'Сменить тему'}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.getByRole('button',{name:'EN',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Security',exact:true})).toBeVisible();
 await page.screenshot({path:'.runtime/ui-security-dark.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Task board',exact:false}).click();
 await page.screenshot({path:'.runtime/ui-mobile-dark.png',fullPage:true});
});
